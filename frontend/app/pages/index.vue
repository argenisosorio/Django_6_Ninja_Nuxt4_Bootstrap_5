<template>
  <div>
    <h1>
      <img
        src="/images/star.png"
        alt="star"
        class="img-fluid mb-3"
        width="50px"
      >
      Django 6 + Django Ninja + Nuxt 4 + Bootstrap 5
    </h1>
    <p>
      Example project showcasing API consumption from Django 6 + Django Ninja
      using Nuxt 4 + Bootstrap 5. Built as a reference implementation
      for developers building full-stack JavaScript/Python applications with
      decoupled architecture.
    </p>
    <button @click="generarPDF">Descargar PDF</button>
  </div>
</template>

<script setup>
useHead({
  title: 'Home'
})

const loader = useState('loader')

onMounted(() => {
  console.log("Activo el loader")
  loader.value = true

  setTimeout(() => {
    loader.value = false
    console.log("Ha pasado 1 segundo y quité el loader")
  }, 1000)
})

const pdfMake = usePDFMake();

const generarPDF = () => {
  const dd = {
    content: [
      { text: '¡Hola desde Nuxt!', style: 'header' },
      'Este PDF fue generado usando el módulo nuxt-pdfmake.'
    ],
    styles: { header: { fontSize: 22, bold: true } }
  };
  pdfMake.createPdf(dd).download('ejemplo-nuxt.pdf');
};
</script>


